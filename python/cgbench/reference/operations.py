"""Capabilities needed by the independent reference iteration engine."""

from contextlib import AbstractContextManager
from typing import Any, Protocol


class ArrayOperations(Protocol):
    rhs: Any
    initial: Any

    @property
    def initial_nbytes(self) -> int: ...

    def snapshot_matrix(self) -> None: ...
    def execution_context(self) -> AbstractContextManager: ...
    def workspace(self) -> list[Any]: ...
    def empty_vector(self) -> Any: ...
    def inverse_diagonal(self) -> Any: ...
    def precondition(self, inverse: Any, residual: Any, out: Any) -> None: ...
    def copy(self, source: Any, destination: Any) -> None: ...
    def matvec(self, vector: Any, out: Any) -> None: ...
    def dot(self, left: Any, right: Any) -> float: ...
    def residual(
        self, x: Any, residual: Any, product: Any, explicit: bool
    ) -> None: ...
    def axpy(
        self, alpha: float, source: Any, destination: Any, scratch: Any
    ) -> None: ...
    def direction(
        self, beta: float, residual: Any, direction: Any, explicit: bool
    ) -> None: ...
    def initialize_direction(
        self, residual: Any, direction: Any, explicit: bool
    ) -> None: ...
    def export(self, x: Any) -> Any: ...
    def outcome_x(self, x: Any) -> Any: ...
